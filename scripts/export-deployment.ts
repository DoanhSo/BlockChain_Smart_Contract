import { readFile, writeFile, mkdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { network } from "hardhat";
import { getAddress, isAddress } from "viem";

const connection = await network.create();
try {
  const client = await connection.viem.getPublicClient();
  const chainId = await client.getChainId();
  if (![31337, 11155111].includes(chainId)) throw new Error("Unsupported chain.");
  const addresses = JSON.parse(await readFile(new URL(`../ignition/deployments/chain-${chainId}/deployed_addresses.json`, import.meta.url), "utf8"));
  const raw: unknown = addresses["VotingModule#Voting"];
  if (typeof raw !== "string" || !isAddress(raw)) throw new Error("Missing Voting deployment.");
  const address = getAddress(raw);
  if (!await client.getCode({ address })) throw new Error("Deployment has no bytecode.");
  const voting = await connection.viem.getContractAt("Voting", address);
  // The journal remains the source of deployment receipts; this is a readback manifest.
  const manifest = {
    chainId, address, contract: "Voting", compiler: "0.8.34", buildProfile: "production",
    title: await voting.read.electionTitle(), admin: await voting.read.admin(),
    observedAtBlock: String(await client.getBlockNumber()),
    sourceCommit: execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim(),
    sourceDirty: execFileSync("git", ["status", "--porcelain"], { encoding: "utf8" }).trim().length > 0,
    ignitionJournal: `ignition/deployments/chain-${chainId}/journal.jsonl`,
  };
  const folder = new URL("../deployments/", import.meta.url);
  await mkdir(folder, { recursive: true });
  await writeFile(new URL(chainId === 31337 ? "local.json" : "sepolia.json", folder), JSON.stringify(manifest, null, 2) + "\n");
  await writeFile(new URL("../frontend/.env.local", import.meta.url),
    `# Public deployment configuration generated by export-deployment.ts\nVITE_CHAIN_ID=${chainId}\nVITE_VOTING_ADDRESS=${address}\n${chainId === 31337 ? "VITE_RPC_URL=http://127.0.0.1:8545\n" : "# Set VITE_RPC_URL to a browser-safe Sepolia endpoint; never copy deploy secrets.\n"}`,
    { flag: "wx" }).catch((error: NodeJS.ErrnoException) => {
      if (error.code !== "EEXIST") throw error;
      console.log("frontend/.env.local already exists; update its address/chain manually if deployment changed.");
    });
  console.log(JSON.stringify(manifest, null, 2));
} finally { await connection.close(); }
